//! The model text format shared with Lean (`HP.parseEnsemble`).
//!
//! ```text
//! gbt <features> <trees> <base>
//! <tree in pre-order: `N <feature> <threshold> <left> <right>` or `L <value>`>   one line per tree
//! ```
//! Numbers are plain decimals (`-12.5`, `3`), never exponents. Lean reads each
//! one as an exact `Rat`. Thresholds are dyadic and written with their exact
//! value, so Lean compares against the very `f64` Rust uses. Leaves and the
//! base are written as the shortest decimal that parses back to the same
//! `f64`; leaves are whole cents.

use crate::features::N;
use crate::tree::{Ensemble, Node};
use std::fmt::Write;

fn num(x: f64) -> String {
    let s = format!("{x}");
    assert!(
        !s.contains('e') && !s.contains("inf") && !s.contains("NaN"),
        "bad number {s}"
    );
    s
}

fn write_node(out: &mut String, n: &Node) {
    match n {
        Node::Leaf(v) => {
            let _ = write!(out, "L {} ", num(*v));
        }
        Node::Split {
            feat,
            thr,
            left,
            right,
        } => {
            // thresholds are dyadic: write their exact value (see `short_between`)
            let t = crate::tree::exact_decimal(*thr)
                .unwrap_or_else(|| panic!("threshold {thr} is not m / 2^k with k <= 30"));
            let _ = write!(out, "N {feat} {t} ");
            write_node(out, left);
            write_node(out, right);
        }
    }
}

pub fn to_text(m: &Ensemble) -> String {
    let mut out = format!("gbt {N} {} {}\n", m.trees.len(), num(m.base));
    for t in &m.trees {
        write_node(&mut out, t);
        out.pop();
        out.push('\n');
    }
    out
}

pub fn from_text(s: &str) -> Result<Ensemble, String> {
    let mut tok = s.split_ascii_whitespace();
    let mut next = || tok.next().ok_or_else(|| "unexpected end".to_string());
    if next()? != "gbt" {
        return Err("expected gbt".into());
    }
    let nf: usize = next()?.parse().map_err(|e| format!("{e}"))?;
    if nf != N {
        return Err(format!("model has {nf} features, expected {N}"));
    }
    let nt: usize = next()?.parse().map_err(|e| format!("{e}"))?;
    let base: f64 = next()?.parse().map_err(|e| format!("{e}"))?;
    fn node(next: &mut dyn FnMut() -> Result<String, String>) -> Result<Node, String> {
        match next()?.as_str() {
            "L" => Ok(Node::Leaf(next()?.parse().map_err(|e| format!("{e}"))?)),
            "N" => {
                let feat: usize = next()?.parse().map_err(|e| format!("{e}"))?;
                if feat >= N {
                    return Err(format!("feature {feat}"));
                }
                let thr: f64 = next()?.parse().map_err(|e| format!("{e}"))?;
                let left = Box::new(node(next)?);
                let right = Box::new(node(next)?);
                Ok(Node::Split {
                    feat,
                    thr,
                    left,
                    right,
                })
            }
            t => Err(format!("unexpected token {t}")),
        }
    }
    let mut nx = || next().map(|s| s.to_string());
    let trees = (0..nt)
        .map(|_| node(&mut nx))
        .collect::<Result<Vec<_>, _>>()?;
    Ok(Ensemble { base, trees })
}

/// FNV-1a, 64 bit: a content stamp, not a security hash.
fn fnv1a(s: &str) -> u64 {
    s.bytes().fold(0xcbf2_9ce4_8422_2325, |h, b| {
        (h ^ b as u64).wrapping_mul(0x100_0000_01b3)
    })
}

/// `lean/HousePricing/Trained.lean`. Lake does not track files read with
/// `include_str`, so the stamps below change whenever a model changes, and
/// that makes Lake rebuild this module and everything that imports it.
pub fn trained_lean(chosen: &str, monotone: &str) -> String {
    format!(
        r#"import HousePricing.Parse
import HousePricing.Features

/-!
# The trained models

Generated by `cargo run --release -- train` in `rust/` (do not edit by hand).

* `chosen` (`model/gbt.txt`): the best model on validation that Lean
  replicates exactly. Gradient boosting, see `model/report.md`.
* `monotone` (`model/gbt-monotone.txt`): the same learner trained with a
  monotone constraint on `median_income`. It scores slightly lower, but
  `Examples.lean` certifies its monotonicity.

If a file does not parse, the model is the empty ensemble (predicts 0);
`Examples.lean` checks that both parse.

Content stamps (FNV-1a): chosen {:016x}, monotone {:016x}.
-/

namespace HP

def chosenText : String := include_str "../../model/gbt.txt"
def monotoneText : String := include_str "../../model/gbt-monotone.txt"

def chosen : Ensemble F := (parseEnsemble F chosenText).getD default
def monotone : Ensemble F := (parseEnsemble F monotoneText).getD default

end HP
"#,
        fnv1a(chosen),
        fnv1a(monotone)
    )
}
